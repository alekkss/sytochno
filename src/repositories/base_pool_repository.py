"""Абстрактный базовый репозиторий пула ID объявлений."""

from abc import ABC, abstractmethod
from datetime import datetime

from src.models.pool import PoolEntry


class BasePoolRepository(ABC):
    """Абстрактный репозиторий пула ID объявлений.

    Пул — отдельная таблица со списком ID, с которыми работает этап
    batch-обогащения. В отличие от таблицы listings, пул хранит только
    ID и метаданные его появления, без данных объявлений.

    Семантика операций:
    - Добавление идемпотентно: повторная вставка существующего ID
      игнорируется (дублей не создаётся ни при каких сценариях).
    - Удаление из пула не предусмотрено (требование: устаревшие ID
      не удаляются — только накапливаются новые).
    - update_last_seen обновляет метку последнего обнаружения ID
      в каталоге при плановой синхронизации.
    """

    @abstractmethod
    def initialize(self) -> None:
        """Инициализирует хранилище (создаёт таблицу пула).

        Вызывается один раз при старте приложения. Безопасен для
        повторного вызова — существующая таблица не пересоздаётся.
        """

    @abstractmethod
    def add_entries(self, entries: list[PoolEntry]) -> int:
        """Добавляет записи в пул, пропуская уже существующие ID.

        Args:
            entries: Записи для добавления.

        Returns:
            Количество реально добавленных записей (без дублей).
        """

    @abstractmethod
    def exists_ids(self, external_ids: set[str]) -> set[str]:
        """Возвращает подмножество ID, которые уже есть в пуле.

        Используется для diff-вычисления при синхронизации каталога:
        новые ID = собранные - существующие.

        Args:
            external_ids: Набор ID для проверки.

        Returns:
            Подмножество external_ids, присутствующее в пуле.
        """

    @abstractmethod
    def get_all_ids(self) -> list[str]:
        """Возвращает все ID из пула.

        Основной метод для этапа batch-обогащения: порядок не гарантирован,
        состав — все когда-либо добавленные ID.

        Returns:
            Список всех ID пула.
        """

    @abstractmethod
    def update_last_seen(
        self,
        external_ids: set[str],
        now: datetime,
    ) -> int:
        """Обновляет метку last_seen_at для перечисленных ID.

        Вызывается после успешной синхронизации каталога для всех
        собранных ID (включая только что добавленные). ID, отсутствующие
        в пуле, молча пропускаются.

        Args:
            external_ids: Набор ID, замеченных в каталоге.
            now: Метка времени синхронизации (UTC).

        Returns:
            Количество обновлённых записей.
        """

    @abstractmethod
    def count(self) -> int:
        """Возвращает общее количество записей в пуле.

        Returns:
            Количество записей.
        """

    @abstractmethod
    def close(self) -> None:
        """Закрывает соединение с хранилищем и освобождает ресурсы."""
